// Batman often declares "I'm Batman" as a way to instill fear in criminals and assert his identity. It emphasizes his determination and signifies that he is a force to be reckoned with.

// Batman decided to instill fear in n
//  of Gotham's most dangerous criminals today by sending "I'm Batman" to every criminal, so he told Alfred to do that task, Alfred is too tired to write all this so he asked for your help.

// Given n
//  the number of criminals Batman wants to scare, Print "I'm Batman" n
//  times

// Input
// one line containing n
//  (1≤n≤1000
// ), The number of criminals Batman wants to scare.

// Output
// n
//  lines, each containing "I'm Batman" without the quotes.

#include <iostream>
using namespace std;
int main(){
    int n;
    cin>> n;
    for(int i=1 ; i<=n ; i++){
        cout<<"I'm Batman\n";
    }
}